import asyncio

from kernel import Kernel
from kernel_events import KernelEventType


async def main():

    print("=" * 70)
    print("KERNEL → DISPATCHER FAILURE EVENT TEST")
    print("=" * 70)

    kernel = Kernel()

    received_events = []

    # --------------------------------------------------
    # DISPATCHER HANDLER
    # --------------------------------------------------

    def handler(event):

        received_events.append(event.event_type)

        print(
            f"[DISPATCHER] "
            f"{event.event_type.value}"
        )

    # --------------------------------------------------
    # SUBSCRIBE TO FAILURE LIFECYCLE
    # --------------------------------------------------

    lifecycle_events = [
        KernelEventType.TASK_STARTED,
        KernelEventType.TOOL_STARTED,
        KernelEventType.TOOL_FAILED,
        KernelEventType.TASK_FAILED,
    ]

    for event_type in lifecycle_events:

        kernel.event_dispatcher.subscribe(
            event_type,
            handler
        )

    # --------------------------------------------------
    # START TASK
    # --------------------------------------------------

    task = kernel.start_task(
        "Turn on the bedroom light."
    )

    # --------------------------------------------------
    # EXECUTE INVALID TOOL REQUEST
    #
    # Missing required "device" argument.
    # This should produce TOOL_FAILED.
    # --------------------------------------------------

    result = await kernel.execute_tool(
        "smart_home",
        task.task_id,
        action="turn_on",
    )

    assert result.success is False

    # --------------------------------------------------
    # FAIL TASK
    #
    # Current Kernel API takes no positional argument.
    # The failure event is generated by the Kernel.
    # --------------------------------------------------

    kernel.fail_current_task()

    await asyncio.sleep(0.1)

    # --------------------------------------------------
    # EXPECTED EVENT ORDER
    # --------------------------------------------------

    expected_events = [
        KernelEventType.TASK_STARTED,
        KernelEventType.TOOL_STARTED,
        KernelEventType.TOOL_FAILED,
        KernelEventType.TASK_FAILED,
    ]

    assert received_events == expected_events, (
        f"\nExpected:\n{expected_events}"
        f"\nReceived:\n{received_events}"
    )

    # --------------------------------------------------
    # VERIFY EVENT STREAM
    # --------------------------------------------------

    stored_events = (
        kernel.event_stream.get_task_events(
            task.task_id
        )
    )

    stored_types = [
        event.event_type
        for event in stored_events
    ]

    assert stored_types == expected_events

    # --------------------------------------------------
    # VERIFY TASK ID CONSISTENCY
    # --------------------------------------------------

    for event in stored_events:

        assert event.task_id == task.task_id

    # --------------------------------------------------
    # VERIFY TOOL FAILURE DATA
    # --------------------------------------------------

    tool_failed_event = next(
        event
        for event in stored_events
        if event.event_type
        == KernelEventType.TOOL_FAILED
    )

    assert tool_failed_event.error is not None

    # --------------------------------------------------
    # VERIFY TASK FAILURE EVENT
    # --------------------------------------------------

    task_failed_event = next(
        event
        for event in stored_events
        if event.event_type
        == KernelEventType.TASK_FAILED
    )

    assert task_failed_event is not None

    # --------------------------------------------------
    # FINAL OUTPUT
    # --------------------------------------------------

    print()
    print(
        f"Dispatched failure events: "
        f"{len(received_events)}"
    )

    print(
        f"Stored failure events: "
        f"{len(stored_events)}"
    )

    print()
    print("TASK_STARTED       ✓")
    print("TOOL_STARTED       ✓")
    print("TOOL_FAILED        ✓")
    print("TASK_FAILED        ✓")
    print("Failure data       ✓")

    print()
    print(
        "KERNEL → DISPATCHER FAILURE "
        "EVENT TEST PASSED"
    )


if __name__ == "__main__":
    asyncio.run(main())